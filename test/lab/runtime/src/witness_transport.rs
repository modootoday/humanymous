//! Roadmap 2b lab actors for the Docker `runtime-binary-witness-transport`
//! case (runtime-application SoT, "Shipped-binary inherited witness input").
//!
//! `--witness-transport-supervisor` is the trusted lab supervisor. It holds the
//! runner's synthetic keys, starts the separate `audit-witness` process, sends
//! that process its private first frame, and lets the shipped
//! `humanymous-runtime` binary inherit the runtime-side pipe ends through
//! `audit.witness_input`. It never judges a case: each step answers one runner
//! command with raw observations (readiness bytes, exit status, HTTP status and
//! body, the WAL's records and checkpoints), and the host runner evaluates them.
//!
//! `--witness-transport-origin` is the owned origin in its own container that
//! shares the supervisor's loopback namespace. It prints every TCP contact to
//! its own stdout before reading, so the runner counts contacts from
//! `docker logs` instead of trusting the supervisor.
use crate::client::{report, request, sign, wire};
use humanymous_runtime::{
    audit::{
        checkpoint::service::{WitnessServiceBootstrap, WitnessServiceConfig, write_frame},
        keys::{
            KeyMaterial,
            custody::{Custody, Owner},
        },
        storage::{Wal, WalOptions},
    },
    gateway::{configuration::Configuration, http::Request},
};
use rustix::io::{FdFlags, fcntl_setfd};
use serde::Deserialize;
use serde_json::{Value, json};
use std::{
    fs,
    io::{BufRead, BufReader, Read, Write},
    net::{SocketAddr, TcpListener, TcpStream},
    os::{
        fd::AsRawFd,
        unix::fs::{DirBuilderExt, PermissionsExt},
    },
    path::{Path, PathBuf},
    process::{Child, ChildStdin, ChildStdout, Command, Stdio},
    sync::mpsc,
    time::{Duration, Instant},
};
use zeroize::Zeroizing;

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

/// Fixed owned origin address inside the shared loopback namespace.
pub const ORIGIN: &str = "127.0.0.1:18090";
const NODE: &str = "witness-transport-node";
const RUNTIME: &str = "/usr/local/bin/humanymous-runtime";
const WITNESS: &str = "/usr/local/bin/audit-witness";

/// Private runner control line: synthetic keys generated by the runner.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Control {
    writer_seed: [u8; 32],
    hmac: [u8; 32],
    witness_seed: [u8; 32],
    witness_public: [u8; 32],
    writer_public: [u8; 32],
    wrong_witness_public: [u8; 32],
    writer_passphrase: String,
    witness_passphrase: String,
}

struct Process(Child);
impl Drop for Process {
    fn drop(&mut self) {
        let _ = self.0.kill();
        let _ = self.0.wait();
    }
}

struct Layout {
    root: PathBuf,
}
impl Layout {
    fn path(&self, name: &str) -> PathBuf {
        self.root.join(name)
    }
}
impl Drop for Layout {
    fn drop(&mut self) {
        if self.root.starts_with(std::env::temp_dir()) {
            let _ = fs::remove_dir_all(&self.root);
        }
    }
}

fn private(path: &Path) -> Result<()> {
    fs::DirBuilder::new().mode(0o700).create(path)?;
    fs::set_permissions(path, fs::Permissions::from_mode(0o700))?;
    Ok(())
}

fn provision(directory: &Path, passphrase: &[u8], seed: [u8; 32], hmac: Vec<u8>) -> Result<()> {
    private(directory)?;
    let mut custody = Custody::acquire(directory, Owner::CurrentUser)?;
    custody.load_or_create(passphrase, || KeyMaterial::new(seed, hmac, None, None))?;
    Ok(())
}

fn entries(directory: &Path) -> usize {
    fs::read_dir(directory).map_or(0, |entries| entries.count())
}

/// Start one `audit-witness` with its private first frame already delivered.
fn witness(
    layout: &Layout,
    control: &Control,
    head: &str,
) -> Result<(Process, ChildStdin, ChildStdout)> {
    let mut child = Command::new(WITNESS)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()?;
    let mut input = child.stdin.take().ok_or("witness stdin")?;
    let output = child.stdout.take().ok_or("witness stdout")?;
    let process = Process(child);
    write_frame(
        &mut input,
        &WitnessServiceConfig {
            key_directory: layout.path("witness-keys"),
            state_directory: layout.path(head),
            owner_sid: None,
            passphrase: Zeroizing::new(control.witness_passphrase.as_bytes().to_vec()),
            writer_public: control.writer_public,
            node_id: NODE.into(),
            bootstrap: WitnessServiceBootstrap::CreateNew,
        },
    )?;
    // Only the two runtime-side ends become inheritable; the runtime is the
    // next and only child spawned while they are.
    fcntl_setfd(&input, FdFlags::empty())?;
    fcntl_setfd(&output, FdFlags::empty())?;
    Ok((process, input, output))
}

fn configuration(
    layout: &Layout,
    control: &Control,
    pinned: [u8; 32],
    read_fd: i32,
    write_fd: i32,
) -> Value {
    json!({"listen":"127.0.0.1:0","origin":ORIGIN,
      "scope":{"installation":"witness-transport","tenant":"lab","origin":"origin","revision":"r1","authority":"owned.test"},
      "routes":[{"method":"POST","path":"/effect","required":{"raw_tls":false,"original_h2":false,"raw_header_order":true,"collector":false,"rit":true}}],
      "audit":{"directory":layout.path("audit"),"node_id":NODE,
        "keys":{"directory":layout.path("writer-keys"),"passphrase":control.writer_passphrase},
        "allow_new":true,"trusted_head":null,"require_external_witness":true,
        "witness_input":{"read_fd":read_fd,"write_fd":write_fd,"witness_public":pinned,
          "writer_public":control.writer_public,"durability":"file_and_directory"}},
      "owner":{"kind":"unix","uid":65532},"session_capacity":16,"session_ttl_ms":60_000,"timeout_ms":5000,"rate_per_second":100})
}

/// The public part of the witness input this supervisor actually configured.
fn configured_input(config: &Value) -> Value {
    let input = &config["audit"]["witness_input"];
    json!({"read_fd":input["read_fd"],"write_fd":input["write_fd"],"witness_public":input["witness_public"],
        "writer_public":input["writer_public"],"durability":input["durability"],
        "require_external_witness":config["audit"]["require_external_witness"]})
}

/// Spawn the shipped binary; return it and its raw first stdout line, which
/// is empty when it exited without readiness within the deadline.
fn runtime(config: &Value) -> Result<(Process, String)> {
    let mut child = Command::new(RUNTIME)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()?;
    let mut input = child.stdin.take().ok_or("runtime stdin")?;
    let stdout = child.stdout.take().ok_or("runtime stdout")?;
    let process = Process(child);
    input.write_all(&serde_json::to_vec(config)?)?;
    drop(input);
    let (send, receive) = mpsc::channel();
    std::thread::spawn(move || {
        let mut line = String::new();
        let result = BufReader::new(stdout).take(1 << 20).read_line(&mut line);
        let _ = send.send(result.map(|_| line));
    });
    let line = receive
        .recv_timeout(Duration::from_secs(20))
        .unwrap_or(Ok(String::new()))?;
    Ok((process, line))
}

fn exit_code(process: &mut Process, seconds: u64) -> Result<Option<i32>> {
    let deadline = Instant::now() + Duration::from_secs(seconds);
    loop {
        if let Some(status) = process.0.try_wait()? {
            return Ok(Some(status.code().unwrap_or(-1)));
        }
        if Instant::now() > deadline {
            return Ok(None);
        }
        std::thread::sleep(Duration::from_millis(10));
    }
}

/// One HTTP/1.1 exchange; a transport failure is recorded, not hidden.
fn exchange(address: SocketAddr, req: &Request) -> Value {
    let attempt = || -> std::io::Result<Vec<u8>> {
        let mut stream = TcpStream::connect_timeout(&address, Duration::from_secs(5))?;
        stream.set_read_timeout(Some(Duration::from_secs(8)))?;
        stream.set_write_timeout(Some(Duration::from_secs(5)))?;
        stream.write_all(&wire(req))?;
        let mut bytes = Vec::new();
        stream.take(1 << 20).read_to_end(&mut bytes)?;
        Ok(bytes)
    };
    match attempt() {
        Ok(bytes) => {
            let status = bytes
                .get(9..12)
                .and_then(|code| std::str::from_utf8(code).ok())
                .and_then(|code| code.parse::<u16>().ok());
            let body = bytes
                .windows(4)
                .position(|w| w == b"\r\n\r\n")
                .map(|end| String::from_utf8_lossy(&bytes[end + 4..]).into_owned());
            json!({"status":status,"body":body})
        }
        Err(_) => json!({"status":null,"transport_error":true}),
    }
}

/// A session response carries a usable capability: relay only its status,
/// whether a session was issued, and an error code.
fn redacted(response: &Value) -> Value {
    let body: Value = response["body"]
        .as_str()
        .and_then(|body| serde_json::from_str(body).ok())
        .unwrap_or(Value::Null);
    let error = body["error"]
        .as_str()
        .map(|code| json!({ "error": code }).to_string());
    json!({"status":response["status"],"issued":body["session"].is_string(),"body":error})
}

struct Session {
    address: SocketAddr,
    typed: Configuration,
    issued: Value,
}

fn step_wrong_key(layout: &Layout, control: &Control) -> Result<Value> {
    let (mut witness_process, input, output) = witness(layout, control, "refused-head")?;
    let config = configuration(
        layout,
        control,
        control.wrong_witness_public,
        output.as_raw_fd(),
        input.as_raw_fd(),
    );
    let (mut process, line) = runtime(&config)?;
    drop(input);
    drop(output);
    let exit = exit_code(&mut process, 20)?;
    let _ = witness_process.0.kill();
    let _ = witness_process.0.wait();
    Ok(
        json!({"step":"wrong_key","configured":configured_input(&config),
        "readiness_line":line,"exit_code":exit,"audit_entries":entries(&layout.path("audit"))}),
    )
}

fn step_witnessed(
    layout: &Layout,
    control: &Control,
    state: &mut Option<(Process, Process, Session)>,
) -> Result<Value> {
    let (witness_process, input, output) = witness(layout, control, "witness-head")?;
    let config = configuration(
        layout,
        control,
        control.witness_public,
        output.as_raw_fd(),
        input.as_raw_fd(),
    );
    let (runtime_process, line) = runtime(&config)?;
    // Close the supervisor's copies once the runtime inherited them.
    drop(input);
    drop(output);
    let mut exchanges = Vec::new();
    let ready: Option<Value> = serde_json::from_str(&line).ok();
    if let Some(address) = ready
        .as_ref()
        .and_then(|ready| ready["listen"].as_str())
        .and_then(|listen| listen.parse::<SocketAddr>().ok())
    {
        let typed: Configuration = serde_json::from_value(config.clone())?;
        let session = exchange(address, &request("/_humanymous/session", vec![]));
        exchanges.push(json!({"name":"session","response":redacted(&session)}));
        let issued: Value = session["body"]
            .as_str()
            .and_then(|body| serde_json::from_str(body).ok())
            .unwrap_or(Value::Null);
        if issued["session"].is_string() && issued["key"].is_string() {
            let mut collect = request("/_humanymous/collect", report(&issued));
            sign(&typed, &mut collect, &issued, 1);
            exchanges.push(json!({"name":"collect","response":exchange(address,&collect)}));
            let mut effect = request("/effect", b"effect".to_vec());
            sign(&typed, &mut effect, &issued, 2);
            exchanges.push(json!({"name":"effect","response":exchange(address,&effect)}));
            *state = Some((
                witness_process,
                runtime_process,
                Session {
                    address,
                    typed,
                    issued,
                },
            ));
        }
    }
    Ok(
        json!({"step":"witnessed","configured":configured_input(&config),"readiness_line":line,
        "witness_head_entries":entries(&layout.path("witness-head")),"exchanges":exchanges}),
    )
}

fn step_witness_loss(state: &mut Option<(Process, Process, Session)>) -> Result<Value> {
    let Some((witness_process, runtime_process, session)) = state.as_mut() else {
        return Ok(json!({"step":"witness_loss","witnessed_session":false}));
    };
    witness_process.0.kill()?;
    let killed = witness_process.0.wait()?;
    let mut effect = request("/effect", b"effect".to_vec());
    sign(&session.typed, &mut effect, &session.issued, 3);
    let after = exchange(session.address, &effect);
    let mut again = request("/effect", b"effect".to_vec());
    sign(&session.typed, &mut again, &session.issued, 4);
    let repeated = exchange(session.address, &again);
    let issue = exchange(session.address, &request("/_humanymous/session", vec![]));
    let alive = runtime_process.0.try_wait()?.is_none();
    Ok(
        json!({"step":"witness_loss","witnessed_session":true,"witness_exit_success":killed.success(),
        "exchanges":[{"name":"effect","response":after},{"name":"effect_repeated","response":repeated},
            {"name":"session","response":redacted(&issue)}],"runtime_alive":alive}),
    )
}

fn step_evidence(
    layout: &Layout,
    state: &mut Option<(Process, Process, Session)>,
) -> Result<Value> {
    // Stop the runtime first: the WAL writer lock is per process lifetime.
    *state = None;
    let wal = Wal::open(&layout.path("audit"), WalOptions::default())?;
    let records = wal.records()?;
    let checkpoints = wal.checkpoints()?;
    Ok(json!({"step":"evidence","records":records,"checkpoints":checkpoints}))
}

/// Trusted lab supervisor: one JSON line in, one JSON line out per step.
pub fn supervisor() -> Result<()> {
    let mut input = BufReader::new(std::io::stdin().lock());
    let mut stdout = std::io::stdout();
    let mut line = Zeroizing::new(String::new());
    input.by_ref().take(64 * 1024).read_line(&mut line)?;
    let control: Control = serde_json::from_str(&line)?;
    drop(line);
    let mut nonce = [0_u8; 8];
    getrandom::fill(&mut nonce)?;
    let name: String = nonce.iter().map(|b| format!("{b:02x}")).collect();
    let root = std::env::temp_dir().join(format!("witness-transport-{name}"));
    private(&root)?;
    let layout = Layout {
        root: root.canonicalize()?,
    };
    for name in ["audit", "refused-head", "witness-head"] {
        private(&layout.path(name))?;
    }
    provision(
        &layout.path("writer-keys"),
        control.writer_passphrase.as_bytes(),
        control.writer_seed,
        control.hmac.to_vec(),
    )?;
    let mut witness_hmac = vec![0; 32];
    getrandom::fill(&mut witness_hmac)?;
    provision(
        &layout.path("witness-keys"),
        control.witness_passphrase.as_bytes(),
        control.witness_seed,
        witness_hmac,
    )?;
    writeln!(stdout, "{}", json!({"role":"wtx_supervisor_ready"}))?;
    stdout.flush()?;
    let mut state = None;
    loop {
        let mut line = String::new();
        if input.by_ref().take(4096).read_line(&mut line)? == 0 {
            break;
        }
        let command: Value = serde_json::from_str(&line)?;
        let reply = match command["step"].as_str() {
            Some("wrong_key") => step_wrong_key(&layout, &control)?,
            Some("witnessed") => step_witnessed(&layout, &control, &mut state)?,
            Some("witness_loss") => step_witness_loss(&mut state)?,
            Some("evidence") => step_evidence(&layout, &mut state)?,
            _ => return Err("unknown supervisor step".into()),
        };
        writeln!(stdout, "{reply}")?;
        stdout.flush()?;
    }
    Ok(())
}

fn serve_contact(stream: &mut TcpStream) {
    let _ = stream.set_read_timeout(Some(Duration::from_secs(5)));
    let mut bytes = Vec::new();
    let mut part = [0; 4096];
    loop {
        if let Some(end) = bytes.windows(4).position(|w| w == b"\r\n\r\n") {
            let length = String::from_utf8_lossy(&bytes[..end])
                .lines()
                .filter_map(|line| line.split_once(':'))
                .find(|(name, _)| name.eq_ignore_ascii_case("content-length"))
                .and_then(|(_, value)| value.trim().parse::<usize>().ok())
                .unwrap_or(0);
            if bytes.len() >= end + 4 + length {
                break;
            }
        }
        match stream.read(&mut part) {
            Ok(0) | Err(_) => break,
            Ok(n) => bytes.extend_from_slice(&part[..n]),
        }
        if bytes.len() > 70_000 {
            break;
        }
    }
    let _ =
        stream.write_all(b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\nConnection: close\r\n\r\nok");
}

/// Owned origin: every contact is printed before parsing.
pub fn origin() -> Result<()> {
    let listener = TcpListener::bind(ORIGIN)?;
    let mut stdout = std::io::stdout();
    writeln!(stdout, "{}", json!({"role":"wtx_origin_ready"}))?;
    stdout.flush()?;
    for (sequence, stream) in listener.incoming().enumerate() {
        let Ok(mut stream) = stream else { continue };
        writeln!(
            stdout,
            "{}",
            json!({"role":"wtx_origin_contact","sequence":sequence + 1})
        )?;
        stdout.flush()?;
        serve_contact(&mut stream);
    }
    Ok(())
}
