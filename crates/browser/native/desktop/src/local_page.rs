//! Immutable owner document. No filesystem lookup, scripts, bridge or URL proxy.
use cef::*;
use std::{
    io,
    sync::{Arc, Mutex},
};

const CSP: &str = "default-src 'none'; script-src 'none'; connect-src 'none'; object-src 'none'; frame-src 'none'; img-src 'none'; style-src 'unsafe-inline'; form-action 'self'; base-uri 'none'";

pub fn register() -> io::Result<()> {
    let bytes = humanymous_browser::newtab::markup()
        .map_err(io::Error::other)?
        .into_bytes();
    let mut factory = OwnerFactory::new(Arc::new(bytes));
    if register_scheme_handler_factory(
        Some(&CefString::from("humanymous")),
        Some(&CefString::from("newtab")),
        Some(&mut factory),
    ) != 1
    {
        return Err(io::Error::other(
            "owner scheme factory registration rejected",
        ));
    }
    Ok(())
}
wrap_scheme_handler_factory! {
    struct OwnerFactory { bytes: Arc<Vec<u8>>, }
    impl SchemeHandlerFactory {
        fn create(&self, _browser: Option<&mut Browser>, _frame: Option<&mut Frame>, _scheme: Option<&CefString>, request: Option<&mut Request>) -> Option<ResourceHandler> {
            let request=request?;
            if CefString::from(&request.url()).to_string()!=humanymous_browser::internal_urls::NEW_TAB_URL
                || CefString::from(&request.method()).to_string()!="GET" { return None; }
            Some(OwnerResource::new(self.bytes.clone(),Arc::new(Mutex::new(0))))
        }
    }
}
wrap_resource_handler! {
    struct OwnerResource { bytes: Arc<Vec<u8>>, position: Arc<Mutex<usize>>, }
    impl ResourceHandler {
        fn open(&self, _request: Option<&mut Request>, handle: Option<&mut i32>, _callback: Option<&mut Callback>) -> i32 {
            if let Some(handle)=handle { *handle=1; 1 } else { 0 }
        }
        fn response_headers(&self, response: Option<&mut Response>, length: Option<&mut i64>, _redirect: Option<&mut CefString>) {
            if let Some(response)=response {
                response.set_status(200); response.set_mime_type(Some(&CefString::from("text/html")));
                response.set_charset(Some(&CefString::from("utf-8")));
                for (key,value) in [("Content-Security-Policy",CSP),("Cache-Control","no-store"),("Referrer-Policy","no-referrer"),("X-Content-Type-Options","nosniff")] {
                    response.set_header_by_name(Some(&CefString::from(key)),Some(&CefString::from(value)),1);
                }
            }
            if let Some(length)=length { *length=self.bytes.len() as i64; }
        }
        fn read(&self, out: *mut u8, capacity: i32, written: Option<&mut i32>, _callback: Option<&mut ResourceReadCallback>) -> i32 {
            let Some(written)=written else { return 0; }; *written=0;
            let Ok(mut position)=self.position.lock() else { return 0; };
            copy_chunk(&self.bytes,&mut position,out,capacity,written)
        }
        fn cancel(&self) { if let Ok(mut position)=self.position.lock() { *position=self.bytes.len(); } }
    }
}

#[allow(unsafe_code)]
fn copy_chunk(
    bytes: &[u8],
    position: &mut usize,
    out: *mut u8,
    capacity: i32,
    written: &mut i32,
) -> i32 {
    *written = 0;
    if out.is_null() || capacity <= 0 || capacity > 16 * 1024 * 1024 || *position >= bytes.len() {
        return 0;
    }
    let count = (capacity as usize).min(bytes.len() - *position);
    // SAFETY: CEF's synchronous read callback lends an output allocation of at
    // least capacity bytes. Bounds/null/integer checks precede this copy; source
    // is immutable owned generated bytes and never overlaps CEF's allocation.
    unsafe {
        std::ptr::copy_nonoverlapping(bytes[*position..].as_ptr(), out, count);
    }
    *position += count;
    *written = count as i32;
    1
}

#[cfg(test)]
mod tests {
    #[test]
    fn synchronous_chunks_are_bounded_and_end_without_leaking_bytes() {
        let mut position = 0;
        let mut output = [0; 4];
        let mut written = 0;
        assert_eq!(
            super::copy_chunk(
                b"abcde",
                &mut position,
                output.as_mut_ptr(),
                4,
                &mut written
            ),
            1
        );
        assert_eq!(&output, b"abcd");
        assert_eq!(written, 4);
        assert_eq!(
            super::copy_chunk(
                b"abcde",
                &mut position,
                output.as_mut_ptr(),
                4,
                &mut written
            ),
            1
        );
        assert_eq!(written, 1);
        assert_eq!(output[0], b'e');
        assert_eq!(
            super::copy_chunk(
                b"abcde",
                &mut position,
                output.as_mut_ptr(),
                4,
                &mut written
            ),
            0
        );
        assert_eq!(written, 0);
        assert_eq!(
            super::copy_chunk(b"a", &mut 0, std::ptr::null_mut(), 4, &mut written),
            0
        );
    }
}
