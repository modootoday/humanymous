//! Declarative planning schema; requirements are not runtime attestation.
use crate::arguments::{Framework, Init};

/// The exact JSON artifact, deterministic for identical explicit options.
#[derive(Debug, serde::Serialize)]
pub struct Manifest<'a> {
    schema: &'static str,
    generator: Generator,
    framework: Framework,
    target: Option<&'a str>,
    runtime_version: Option<&'a str>,
    adapter_package: &'static str,
    integration_status: &'static str,
    qualified: bool,
    available_capabilities: [&'static str; 0],
    requested_policy: Policy,
    host_requirements: Vec<&'static str>,
    unverified: [&'static str; 5],
}

#[derive(Debug, serde::Serialize)]
struct Generator {
    package: &'static str,
    version: &'static str,
}
#[derive(Debug, serde::Serialize)]
struct Policy {
    mode: &'static str,
    sandbox_required: bool,
    renderer_native_access: bool,
    scoring_changes_allowed: bool,
}

/// Build an honest plan for an unimplemented adapter; never inspect the host.
pub fn build(init: &Init) -> Manifest<'_> {
    let adapter_package = match init.framework {
        Framework::Electron => "humanymous-native-electron",
        Framework::Tauri => "humanymous-native-tauri",
        Framework::Winit => "humanymous-native-winit",
        Framework::Dotnet | Framework::Qt | Framework::Flutter => "humanymous-native-ffi",
    };
    let mut host_requirements = vec![
        "Explicit app-owned initialization and bounded shutdown",
        "External host glue is app-owned and not generated by this tool",
        "Qualify the exact OS/architecture/runtime/artifact tuple before use",
    ];
    if init.framework == Framework::Electron {
        host_requirements.extend([
            "Load a Rust Node-API addon in the trusted main process only",
            "Require sandbox=true, contextIsolation=true, nodeIntegration=false",
            "Do not initialize a second CEF or expose raw native authority to renderers",
        ]);
    }
    Manifest {
        schema: "humanymous.native.integration/1",
        generator: Generator {
            package: env!("CARGO_PKG_NAME"),
            version: env!("CARGO_PKG_VERSION"),
        },
        framework: init.framework,
        target: init.target.as_deref(),
        runtime_version: init.runtime_version.as_deref(),
        adapter_package,
        integration_status: "not_implemented",
        qualified: false,
        available_capabilities: [],
        requested_policy: Policy {
            mode: "observe_only",
            sandbox_required: true,
            renderer_native_access: false,
            scoring_changes_allowed: false,
        },
        host_requirements,
        unverified: [
            "SDK/core/FFI lifecycle and actual adapter artifact",
            "Consumer integration and packaged runtime compatibility",
            "Actual sandbox policy and native input delivery",
            "Accessibility/privacy/performance/loss and cleanup",
            "Automation attribution and any separately authorized enforcement",
        ],
    }
}

/// Serialize the manifest completely before publication; output is bounded to16KiB.
pub fn bytes(init: &Init) -> Result<Vec<u8>, String> {
    let mut bytes = serde_json::to_vec_pretty(&build(init)).map_err(|error| error.to_string())?;
    bytes.push(b'\n');
    if bytes.len() > 16384 {
        return Err("manifest budget exceeded".into());
    }
    Ok(bytes)
}
